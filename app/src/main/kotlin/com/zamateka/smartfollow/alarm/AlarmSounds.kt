package com.zamateka.smartfollow.alarm

import android.annotation.SuppressLint
import android.content.ContentResolver
import android.content.Context
import android.media.RingtoneManager
import android.net.Uri
import androidx.annotation.StringRes
import androidx.core.net.toUri
import com.zamateka.smartfollow.R

/**
 * A set of built-in alarm sounds, stored as `res/raw/alarm_<id>_<alarm>`. A private theme, made
 * of files that cannot be published, lives in `app/src/private/res/raw`, which git ignores: it
 * is only offered when its files are in the build.
 */
enum class SoundTheme(
    val id: String,
    @param:StringRes val label: Int,
    /** Whether low soon has its own sound; otherwise it uses the low one. */
    val hasLowSoonSound: Boolean,
) {
    /** Private theme: sound files provided by the user, not in the repository ("Personal"). */
    PRIVATE("private", R.string.sound_theme_private, hasLowSoonSound = true),

    /** Soft chimes generated by `tools/sounds/generate_sounds.py`. */
    DEFAULT("default", R.string.sound_theme_default, hasLowSoonSound = false),
    ;

    fun isAvailable(context: Context): Boolean = AlarmType.entries.all { AlarmSounds.resourceId(context, it, this) != 0 }

    companion object {
        /**
         * The theme with this id if its sounds are in this build. An unknown id (a private theme
         * stored under another id by an older version) means the private theme when its sounds
         * are in this build; otherwise Chimes.
         */
        fun of(context: Context, id: String): SoundTheme {
            val theme = entries.firstOrNull { it.id == id } ?: PRIVATE
            return theme.takeIf { it.isAvailable(context) } ?: DEFAULT
        }

        /** The themes whose sounds are in this build. */
        fun available(context: Context): List<SoundTheme> = entries.filter { it.isAvailable(context) }
    }
}

/**
 * A built-in sound of every theme, named after the alarm it is made for ([type]). An alarm can
 * use another alarm's built-in sound: its `soundUri` is then [AlarmSounds.BUILT_IN_PREFIX] +
 * [key], which follows the chosen theme.
 */
enum class BuiltInSound(val key: String, val type: AlarmType) {
    LOW_SOON("low_soon", AlarmType.LOW_SOON),
    LOW("low", AlarmType.LOW),
    URGENT_LOW("urgent_low", AlarmType.URGENT_LOW),
    HIGH("high", AlarmType.HIGH),
    URGENT_HIGH("urgent_high", AlarmType.URGENT_HIGH),
    STALE_DATA("stale_data", AlarmType.STALE_DATA),
    ;

    companion object {
        /** The built-in sound [type] rings with by default in [theme]. */
        fun defaultFor(type: AlarmType, theme: SoundTheme): BuiltInSound = when (type) {
            AlarmType.URGENT_LOW -> URGENT_LOW
            AlarmType.LOW_SOON -> if (theme.hasLowSoonSound) LOW_SOON else LOW
            AlarmType.FAST_DROP, AlarmType.NO_RECOVERY, AlarmType.LOW -> LOW
            AlarmType.URGENT_HIGH -> URGENT_HIGH
            AlarmType.HIGH -> HIGH
            AlarmType.STALE_DATA -> STALE_DATA
        }

        /** The sounds of [theme], low soon only if it has its own. */
        fun of(theme: SoundTheme): List<BuiltInSound> = entries.filter { it != LOW_SOON || theme.hasLowSoonSound }

        fun ofKey(key: String): BuiltInSound? = entries.firstOrNull { it.key == key }
    }
}

/** What an alarm rings with, read from its `soundUri`. */
sealed interface AlarmSound {
    /** The built-in sound of the alarm in the chosen theme (`soundUri` is `null`). */
    data object Default : AlarmSound

    /** Another alarm's built-in sound, in the chosen theme. */
    data class BuiltIn(val sound: BuiltInSound) : AlarmSound

    /** A sound of the phone, chosen in the system picker. */
    data class Phone(val uri: String) : AlarmSound

    /** The `soundUri` value that stores this choice. */
    fun toSoundUri(): String? = when (this) {
        Default -> null
        is BuiltIn -> AlarmSounds.BUILT_IN_PREFIX + sound.key
        is Phone -> uri
    }

    companion object {
        fun of(soundUri: String?): AlarmSound = when {
            soundUri == null -> Default
            soundUri.startsWith(AlarmSounds.BUILT_IN_PREFIX) ->
                BuiltInSound.ofKey(soundUri.removePrefix(AlarmSounds.BUILT_IN_PREFIX))?.let(::BuiltIn) ?: Default
            else -> Phone(soundUri)
        }
    }
}

/**
 * Sound of each alarm: the ringtone chosen by the user, or a built-in sound of the chosen
 * theme. Built-in sounds differ between urgent low, low, urgent high, high and stale data (and
 * low soon in some themes) so that they can be told apart by ear.
 */
object AlarmSounds {

    /** Prefix of a `soundUri` naming a built-in sound ([AlarmSound.BuiltIn]). */
    const val BUILT_IN_PREFIX = "builtin:"

    /** Name of the built-in sound of [type] in [theme], without extension. */
    fun fileName(type: AlarmType, theme: SoundTheme): String = fileName(BuiltInSound.defaultFor(type, theme), theme)

    fun fileName(sound: BuiltInSound, theme: SoundTheme): String = "alarm_${theme.id}_${sound.key}"

    /**
     * Resource of a built-in sound, 0 if it is not in this build. Looked up by name: a private
     * theme may be missing, so no `R.raw` constant can name its files.
     */
    @SuppressLint("DiscouragedApi")
    fun resourceId(context: Context, type: AlarmType, theme: SoundTheme): Int = resourceId(context, BuiltInSound.defaultFor(type, theme), theme)

    @SuppressLint("DiscouragedApi")
    fun resourceId(context: Context, sound: BuiltInSound, theme: SoundTheme): Int =
        context.resources.getIdentifier(fileName(sound, theme), "raw", context.packageName)

    fun uri(context: Context, type: AlarmType, preferences: AlarmPreferences): Uri {
        val theme = SoundTheme.of(context, preferences.soundTheme)
        return when (val sound = AlarmSound.of(preferences.forType(type).soundUri)) {
            AlarmSound.Default -> builtInUri(context, BuiltInSound.defaultFor(type, theme), theme)
            is AlarmSound.BuiltIn -> builtInUri(context, sound.sound, theme)
            is AlarmSound.Phone -> sound.uri.toUri()
        }
    }

    /** The built-in [sound] of [theme], to play it. */
    fun builtInUri(context: Context, sound: BuiltInSound, theme: SoundTheme): Uri = Uri.Builder()
        .scheme(ContentResolver.SCHEME_ANDROID_RESOURCE)
        .authority(context.packageName)
        .appendPath(resourceId(context, sound, theme).toString())
        .build()

    /** Title of a ringtone chosen by the user, or `null` if it is no longer available. */
    fun ringtoneTitle(context: Context, uri: String): String? =
        runCatching { RingtoneManager.getRingtone(context, uri.toUri())?.getTitle(context) }.getOrNull()

}
